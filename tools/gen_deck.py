GREEN = RGBColor(0x6F, 0xC2, 0x76)

W, H = Emu(12192000), Emu(6858000)          # 16:9


def deck():
    p = Presentation()
    p.slide_width, p.slide_height = W, H
    return p


def blank(prs):
    s = prs.slides.add_slide(prs.slide_layouts[6])
    bg = s.background.fill
    bg.solid()
    bg.fore_color.rgb = BG
    return s


def box(slide, x, y, w, h):
    tb = slide.shapes.add_textbox(Emu(x), Emu(y), Emu(w), Emu(h))
    tf = tb.text_frame
    tf.word_wrap = True
    return tf


def line(tf, text, size=18, color=TEXT, bold=False, space=6, first=False,
         align=PP_ALIGN.LEFT):
    par = tf.paragraphs[0] if first else tf.add_paragraph()
    par.alignment = align
    par.space_after = Pt(space)
    r = par.add_run()
    r.text = text
    r.font.size = Pt(size)
    r.font.bold = bold
    r.font.color.rgb = color
    r.font.name = "Verdana"
    return par


def title_slide(prs, big, sub, note=""):
    s = blank(prs)
    tf = box(s, 900000, 2100000, 10400000, 2600000)
    line(tf, big, 48, SAND, True, 16, first=True)
    line(tf, sub, 22, TEXT, False, 10)
    if note:
        line(tf, note, 15, DIM)
    return s


def head(slide, text, color=SAND):
    tf = box(slide, 700000, 420000, 10800000, 900000)
    line(tf, text, 30, color, True, 0, first=True)


def bullets(slide, items, top=1500000, size=17, gap=8):
    # Подгоняем кегль под длину: иначе хвост списка уезжает за край
    # слайда, и этого не видно, пока не откроешь.
    n = len(items)
    if n > 15:
        size, gap = min(size, 14), 3
    elif n > 12:
        size, gap = min(size, 15), 4
    elif n > 9:
        size, gap = min(size, 16), 6
    tf = box(slide, 700000, top, 10800000, 4800000)
    first = True
    for it in items:
        if isinstance(it, tuple):
            txt, col, bold = it
        else:
            txt, col, bold = it, TEXT, False
        line(tf, txt, size, col, bold, gap, first=first)
        first = False


def table(slide, rows, top=1500000, widths=(3600000, 3400000, 3600000),
          size=15):
    """Простая таблица: строки — списки ячеек, первая строка — шапка."""
    x = 700000
    y = top
    rowh = 330000
    for ri, row in enumerate(rows):
        cx = x
        for ci, cell in enumerate(row):
            tf = box(slide, cx, y, widths[ci], rowh)
            col = DIM if ri == 0 else TEXT
            if ri > 0 and ci == 2:
                col = GREEN if cell.startswith(("стало", "держит", "ровно",
                                                "1.6", "0 ", "да")) else FIRE
            line(tf, cell, size, col, ri == 0, 0, first=True)
            cx += widths[ci]
        y += rowh


