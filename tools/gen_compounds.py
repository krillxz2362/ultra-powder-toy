def mass(f):
    # разбор с круглыми скобками: Ca(OH)2
    def chunk(s):
        tot, i = 0.0, 0
        while i < len(s):
            if s[i] == '(':
                d, j = 1, i+1
                while d:
                    if s[j]=='(': d+=1
                    elif s[j]==')': d-=1
                    j+=1
                inner = chunk(s[i+1:j-1])
                k = re.match(r'\d+', s[j:])
                n = int(k.group()) if k else 1
                tot += inner*n
                i = j + (len(k.group()) if k else 0)
            else:
                m = re.match(r'([A-Z][a-z]?)(\d*)', s[i:])
                if not m: raise ValueError(f + " / " + s[i:])
                el, n = m.group(1), m.group(2)
                if el not in M: raise KeyError(f + " -> " + el)
                tot += M[el] * (int(n) if n else 1)
                i += len(m.group())
        return tot
    return chunk(f)

