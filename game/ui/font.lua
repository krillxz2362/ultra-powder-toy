-- строчные русские приводим к заглавным
local LOWER = {}
do
    local up = "АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ"
    local lo = "абвгдеёжзийклмнопрстуфхцчшщъыьэюя"
    local function chars(s)
        local t, i = {}, 1
        while i <= #s do
            local b = s:byte(i)
            local n = (b < 0x80 and 1) or (b < 0xE0 and 2) or (b < 0xF0 and 3) or 4
            t[#t + 1] = s:sub(i, i + n - 1)
            i = i + n
        end
        return t
    end
    local U, L = chars(up), chars(lo)
    for i = 1, #U do LOWER[L[i]] = U[i] end
    -- Латинские строчные. Нужны для химических символов: без них от «He»
    -- рисовалась одна «H», и таблица элементов читалась как набор букв.
    local la = "abcdefghijklmnopqrstuvwxyz"
    local LA = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
    for i = 1, #la do LOWER[la:sub(i, i)] = LA:sub(i, i) end
end

local GW, GH = 5, 7
local SPACING = 1

local order = {}
local index = {}
for k in pairs(G) do order[#order + 1] = k end
table.sort(order)
for i, k in ipairs(order) do index[k] = i - 1 end

local image, quads

function font.load()
    local n = #order
    local iw, ih = n * (GW + 1), GH
    local data = love.image.newImageData(iw, ih)
    for i, key in ipairs(order) do
        local rows = G[key]
        local ox = (i - 1) * (GW + 1)
        for y = 1, GH do
            local row = rows[y]
            for x = 1, GW do
                if row:sub(x, x) == "#" then
                    data:setPixel(ox + x - 1, y - 1, 1, 1, 1, 1)
                end
            end
        end
    end
    image = love.graphics.newImage(data)
    image:setFilter("nearest", "nearest")
    quads = {}
    for i = 1, n do
        quads[i - 1] = love.graphics.newQuad((i - 1) * (GW + 1), 0, GW, GH, iw, ih)
    end
end

local function split(s)
    local t, i = {}, 1
    while i <= #s do
        local b = s:byte(i)
        local n = (b < 0x80 and 1) or (b < 0xE0 and 2) or (b < 0xF0 and 3) or 4
        t[#t + 1] = s:sub(i, i + n - 1)
        i = i + n
    end
    return t
end

function font.width(text, scale)
    scale = scale or 1
    local n = #split(text)
    if n == 0 then return 0 end
    return (n * (GW + SPACING) - SPACING) * scale
end

function font.height(scale)
    return GH * (scale or 1)
end

-- Рисует текст. Цвет берётся из текущего love.graphics.setColor.
function font.print(text, x, y, scale)
    scale = scale or 1
    local step = (GW + SPACING) * scale
    local cx = x
    for _, ch in ipairs(split(text)) do
        local key = LOWER[ch] or ch
        local id = index[key]
        if id then
            love.graphics.draw(image, quads[id], cx, y, 0, scale, scale)
        end
        cx = cx + step
    end
end

function font.printCentered(text, cx, y, scale)
    font.print(text, cx - font.width(text, scale) * 0.5, y, scale)
end

return font
